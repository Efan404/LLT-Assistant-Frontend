import * as assert from "assert";
import * as fs from "fs";
import * as path from "path";

describe("package-lock.json validations", () => {
  let packageLock: any;

  before(function () {
    const filePath = path.join(__dirname, "package-lock.json");
    const raw = fs.readFileSync(filePath, "utf8");
    packageLock = JSON.parse(raw);
  });

  it("should have valid structure with required fields", () => {
    assert.ok(packageLock.name, "name field exists");
    assert.ok(packageLock.version, "version field exists");
    assert.ok(packageLock.lockfileVersion, "lockfileVersion exists");
    assert.ok(packageLock.packages, "packages object exists");
  });

  it("should have root package entry", () => {
    assert.ok(
      Object.prototype.hasOwnProperty.call(packageLock.packages, ""),
      "root package '' exists"
    );
  });

  it("should have valid semver versions", () => {
    const semverRegex =
      /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/;

    Object.entries(packageLock.packages).forEach(([key, pkg]: [string, any]) => {
      if (!pkg || !pkg.version) return;
      assert.ok(
        semverRegex.test(pkg.version),
        `package ${key} has valid semver: ${pkg.version}`
      );
    });
  });

  it("should not have duplicate package@version entries", () => {
    const map = new Map<string, number>();

    Object.entries(packageLock.packages).forEach(([key, pkg]: [string, any]) => {
      if (!pkg || !pkg.version) return;
      const identifier = `${key}@${pkg.version}`;
      map.set(identifier, (map.get(identifier) || 0) + 1);
    });

    map.forEach((count, identifier) => {
      assert.strictEqual(count, 1, `No duplicate: ${identifier}`);
    });
  });

  it("should have integrity hashes for remote packages", () => {
    Object.entries(packageLock.packages).forEach(([key, pkg]: [string, any]) => {
      if (!pkg || pkg.link === true) return; // skip local links
      if (pkg.resolved && pkg.integrity) {
        assert.ok(
          /^sha(?:256|384|512)/i.test(pkg.integrity),
          `package ${key} has secure hash`
        );
      }
    });
  });

  it("should have at least some packages with licenses", () => {
    const withLicense = Object.values(packageLock.packages).some(
      (p: any) => p && typeof p.license === "string"
    );
    assert.ok(withLicense, "at least one package has a license");
  });
});